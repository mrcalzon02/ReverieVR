#include "breakwater_gun_mesh.h"
#include <cassert>
#include <cmath>
#include <cstddef>
#include <iostream>
#include <limits>
#include <vector>
using namespace reverie::breakwater;
struct Geometry {
    std::vector<float> numbers;
    float min_x=999.f,max_x=-999.f,min_y=999.f,max_y=-999.f,
          min_z=999.f,max_z=-999.f;
    bool all_valid=true;
    void operator()(float x0,float y0,float z0,float x1,float y1,float z1,
                    float x2,float y2,float z2,float r,float g,float b){
        const float values[]={x0,y0,z0,x1,y1,z1,x2,y2,z2,r,g,b};
        for(float value:values){if(!std::isfinite(value))all_valid=false;
            numbers.push_back(value);}
        const float x[]={x0,x1,x2},y[]={y0,y1,y2},z[]={z0,z1,z2};
        for(int i=0;i<3;++i){
            min_x=std::min(min_x,x[i]);max_x=std::max(max_x,x[i]);
            min_y=std::min(min_y,y[i]);max_y=std::max(max_y,y[i]);
            min_z=std::min(min_z,z[i]);max_z=std::max(max_z,z[i]);
        }
    }
};
int main(){
    const float forwards[3]={0.f,0.f,-1.f};
    for(int weapon=0;weapon<kWeaponCount;++weapon){
        Geometry mesh;
        gunmesh::Build([&](auto... v){mesh(v...);},
                        static_cast<WeaponKind>(weapon),forwards);
        assert(mesh.all_valid && mesh.numbers.size()%12u==0u);
        assert(mesh.numbers.size()/12u>240u);
        assert(mesh.numbers.size()/12u<1600u);
        // Forward muzzle is still seawards, while the gun carriage is
        // now seated behind the near-shore targets (not offshore of them).
        assert(mesh.min_z< -.50f && mesh.max_z>.80f);
        assert(mesh.min_x< -.50f && mesh.max_x>.50f); // 3D wheels and shield
        assert(mesh.min_y< -1.20f && mesh.max_y> -.40f);
        Geometry replay;
        gunmesh::Build([&](auto... v){replay(v...);},
                       static_cast<WeaponKind>(weapon),forwards);
        assert(replay.numbers==mesh.numbers);
    }
    // Assert weapon *geometry*, not just labels, skins or firing stats:
    // distinct front assemblies must be generated by the mounted gun path.
    Geometry weaponShapes[kWeaponCount];
    for(uint8_t id=0;id<kWeaponCount;++id)
        gunmesh::Build([&](auto... v){weaponShapes[id](v...);},
                       static_cast<WeaponKind>(id),forwards);
    for(uint8_t a=0;a<kWeaponCount;++a) {
        for(uint8_t b=a+1;b<kWeaponCount;++b) {
            bool different=false;
            const auto &left=weaponShapes[a].numbers;
            const auto &right=weaponShapes[b].numbers;
            if(left.size()!=right.size())different=true;
            else for(size_t n=0;n<left.size();n+=12u)
                // Test XYZ geometry, not its easily-recolored materials.
                for(size_t k=0;k<9u;++k)
                    if(std::abs(left[n+k]-right[n+k])>.0001f)
                        different=true;
            assert(different);
        }
    }
    // An artillery shell's forward section is centered; the missile bank
    // visibly extends above it and flak outboards project to either side.
    const auto countForward=[&](WeaponKind kind,bool (*predicate)(float,float,float)) {
        const auto &mesh=weaponShapes[static_cast<uint8_t>(kind)].numbers;
        size_t count=0;
        for(size_t t=0;t<mesh.size();t+=12u)
            for(size_t vertex=0;vertex<9u;vertex+=3u)
                if(predicate(mesh[t+vertex],mesh[t+vertex+1u],
                             mesh[t+vertex+2u]))++count;
        return count;
    };
    const auto farOutboard=[](float x,float,float z) {
        return z<-.46f && std::abs(x)>.30f;
    };
    const auto highRocket=[](float,float y,float z) {
        return z<-.20f && y>-.26f;
    };
    assert(countForward(WeaponKind::Flak,farOutboard)>0u);
    assert(countForward(WeaponKind::MissileBattery,farOutboard)>0u);
    assert(countForward(WeaponKind::MissileBattery,highRocket)>0u);
    // The newly detailed recoil/breech housings can occupy the upper
    // receiver region on heavy and direct guns; they remain distinct by
    // measured full XYZ geometry, not a false absence-of-hardware rule.
    assert(weaponShapes[static_cast<uint8_t>(WeaponKind::HeavyGun)].numbers.size()>0u);
    assert(weaponShapes[static_cast<uint8_t>(WeaponKind::DirectCannon)].numbers.size()>0u);
    const float aimed[3]={.50f,.27f,-.82f};
    Geometry aimedMesh;
    gunmesh::Build([&](auto... v){aimedMesh(v...);},
                    WeaponKind::DirectCannon,aimed);
    assert(aimedMesh.all_valid && aimedMesh.max_x>.7f);
    assert(aimedMesh.max_y> -.25f); // rotated muzzle clears horizontal mount
    // Confirmed-shot visual pose must retract the moving tube but not
    // teleport the static carriage; particle geometry only exists on fire.
    Geometry firing;
    gunmesh::Build([&](auto... v){firing(v...);},
                    WeaponKind::DirectCannon,forwards,.09f);
    Geometry idle;
    gunmesh::Build([&](auto... v){idle(v...);},
                    WeaponKind::DirectCannon,forwards,0.f);
    assert(firing.all_valid && firing.numbers.size()==idle.numbers.size());
    assert(std::abs(firing.numbers[2]-idle.numbers[2]-.117f)<.0001f);
    // Last triangles are fixed protective shield faces and stay stationary.
    for(size_t i=idle.numbers.size()-48u;i<idle.numbers.size();++i)
        assert(firing.numbers[i]==idle.numbers[i]);
    Geometry spark;
    gunmesh::Flash([&](auto... v){spark(v...);},
                   WeaponKind::DirectCannon,forwards,.09f);
    assert(spark.all_valid && spark.numbers.size()==12u*12u);
    assert(spark.min_z< -.86f && spark.min_z> -1.20f);
    Geometry rejectedSpark;
    gunmesh::Flash([&](auto... v){rejectedSpark(v...);},
                   WeaponKind::DirectCannon,forwards,0.f);
    gunmesh::Flash([&](auto... v){rejectedSpark(v...);},
                   WeaponKind::DirectCannon,forwards,NAN);
    assert(rejectedSpark.numbers.empty());
    assert(gunmesh::RecoilDistance(NAN)==0.f);
    assert(gunmesh::RecoilDistance(-1.f)==0.f);
    assert(gunmesh::RecoilDistance(100.f)<=.12f);
    const float nonfinite[3]={NAN,0.f,-1.f};
    Geometry rejected;
    gunmesh::Build([&](auto... v){rejected(v...);},
                    WeaponKind::MachineGun,nonfinite);
    assert(rejected.numbers.empty());
    // Operator-facing racks stay to the seated player's left and landward.
    assert(gunmesh::kRackX< -1.0f && gunmesh::kRackZ>0.f);
    // Real purchased-weapon previews must lie in the physical pick cuboids.
    const float eye[]={0.f,0.f,0.f};
    for(uint8_t id=0;id<kWeaponCount;++id) {
        const gunmesh::RackSlot slot=gunmesh::RackLocation(id);
        const float ray[]={slot.x,slot.y,slot.z};
        assert(gunmesh::HitRack(eye,ray)==id);
        Geometry miniature;
        gunmesh::RackModel([&](auto... v){miniature(v...);},
                           static_cast<WeaponKind>(id));
        assert(miniature.all_valid && miniature.numbers.size()/12u>240u);
        assert(miniature.min_x>=slot.x-gunmesh::kRackHalfX);
        assert(miniature.max_x<=slot.x+gunmesh::kRackHalfX);
        assert(miniature.min_y>=slot.y-gunmesh::kRackHalfY);
        assert(miniature.max_y<=slot.y+gunmesh::kRackHalfY);
        assert(miniature.min_z>=slot.z-gunmesh::kRackHalfZ);
        assert(miniature.max_z<=slot.z+gunmesh::kRackHalfZ);
    }
    const float right[]={1.f,0.f,-1.f};
    const float behind[]={0.f,0.f,1.f};
    const float bad[]={NAN,0.f,-1.f};
    assert(gunmesh::HitRack(eye,right)==-1);
    assert(gunmesh::HitRack(eye,behind)==-1);
    assert(gunmesh::HitRack(eye,bad)==-1);
    assert(gunmesh::HitRack(nullptr,right)==-1);
    assert(gunmesh::HitRack(eye,nullptr)==-1);
    Geometry nonexistent;
    gunmesh::RackModel([&](auto... v){nonexistent(v...);},
                       static_cast<WeaponKind>(kWeaponCount));
    assert(nonexistent.numbers.empty());
    std::cout<<"Breakwater 3D cannon: 5 mounted shapes, directional elevation, "
             <<"finite deterministic solid mesh passed\n";
}
