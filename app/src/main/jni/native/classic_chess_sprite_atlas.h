inline bool Decode(std::vector<uint8_t>& image){
    image.assign(kPixels*2,0);
    std::size_t total=0;
    for(std::size_t i=0;i+2<sizeof(kRle);i+=3){
        const std::size_t count=kRle[i];
        if(!count||total+count>kPixels)return false;
        const uint8_t l=kRle[i+1],a=kRle[i+2];
        for(std::size_t j=0;j<count;++j){
            const std::size_t local=total+j,tile=local/(kTile*kTile);
            const std::size_t pix=local%(kTile*kTile);
            const std::size_t x=(tile%kColumns)*kTile+pix%kTile;
            const std::size_t y=(tile/kColumns)*kTile+pix/kTile;
            const std::size_t dst=(y*kWidth+x)*2;
            image[dst]=l;image[dst+1]=a;
        }
        total+=count;
    }
    return total==kPixels;
}
